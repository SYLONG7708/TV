import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import babel from '@babel/core';
import presetEnv from '@babel/preset-env';

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const androidRoot = path.resolve(toolDir, '..');
const repositoryRoot = path.resolve(androidRoot, '..');
const inputFile = path.resolve(repositoryRoot, 'docs', 'iphone', 'index.html');
const outputFile = path.resolve(androidRoot, 'app', 'src', 'main', 'assets', 'iphone', 'index.html');

function sha256(value) {
  return `sha256-${crypto.createHash('sha256').update(value, 'utf8').digest('base64')}`;
}

function exactlyOne(html, pattern, label) {
  const matches = [...html.matchAll(pattern)];
  if (matches.length !== 1) throw new Error(`Expected one ${label}; found ${matches.length}.`);
  return matches[0][1];
}

function compatibilityPolicy(style, script) {
  return [
    "default-src 'self'",
    `script-src 'self' '${sha256(script)}' https://cdn.jsdelivr.net https://www.youtube.com`,
    `style-src 'self' '${sha256(style)}'`,
    "img-src 'self' data: https: http:",
    "media-src 'self' blob: https: http:",
    "connect-src 'self' https: http:",
    'frame-src https://www.youtube.com https://www.youtube-nocookie.com',
    "worker-src 'self' blob:",
    "font-src 'self' data:",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
}

const polyfills = `
(function () {
  if (!Object.entries) Object.entries = function (object) {
    return Object.keys(object).map(function (key) { return [key, object[key]]; });
  };
  if (!Object.fromEntries) Object.fromEntries = function (entries) {
    return Array.from(entries).reduce(function (object, entry) {
      object[entry[0]] = entry[1];
      return object;
    }, {});
  };
  if (!Array.prototype.flat) Array.prototype.flat = function (depth) {
    var level = depth === undefined ? 1 : Number(depth) || 0;
    return level > 0
      ? this.reduce(function (output, value) {
          return output.concat(Array.isArray(value) ? value.flat(level - 1) : value);
        }, [])
      : this.slice();
  };
  if (!Array.prototype.flatMap) Array.prototype.flatMap = function (callback, thisArg) {
    return this.map(callback, thisArg).flat(1);
  };
  if (!String.prototype.replaceAll) String.prototype.replaceAll = function (search, replacement) {
    if (search instanceof RegExp) return this.replace(search, replacement);
    return this.split(String(search)).join(replacement);
  };
  if (!Promise.prototype.finally) Promise.prototype.finally = function (callback) {
    var PromiseConstructor = this.constructor;
    return this.then(
      function (value) { return PromiseConstructor.resolve(callback()).then(function () { return value; }); },
      function (reason) { return PromiseConstructor.resolve(callback()).then(function () { throw reason; }); }
    );
  };
  if (window.NodeList && !NodeList.prototype.forEach) NodeList.prototype.forEach = Array.prototype.forEach;
  if (window.HTMLCollection && !HTMLCollection.prototype.forEach) HTMLCollection.prototype.forEach = Array.prototype.forEach;
})();
`;

async function main() {
  let html = (await fs.readFile(inputFile, 'utf8')).replace(/\r\n?/g, '\n');
  const remotePako = /<script\s+src="https:\/\/cdn\.jsdelivr\.net\/npm\/pako@2\.1\.0\/dist\/pako\.min\.js"[^>]*><\/script>/g;
  if ([...html.matchAll(remotePako)].length !== 1) throw new Error('Expected one pako script.');
  html = html.replace(remotePako, '<script src="../assets/pako.min.js" defer></script>');
  const moduleSource = exactlyOne(
    html,
    /<script\s+type="module"\s+data-csp-hash>([\s\S]*?)<\/script>/g,
    'application module',
  )
    .replace(/\/\[\\p\{Script=Han\}A-Za-z0-9\]\/u/g, '/[\\u3400-\\u9fffA-Za-z0-9]/')
    .replace(/\/\\p\{Script=Han\}\/gu/g, '/[\\u3400-\\u9fff]/g');
  const transformed = await babel.transformAsync(moduleSource, {
    sourceType: 'script',
    comments: false,
    compact: false,
    sourceMaps: false,
    presets: [
      [
        presetEnv,
        {
          targets: { chrome: '49' },
          bugfixes: true,
          modules: false,
          useBuiltIns: false,
        },
      ],
    ],
  });
  if (!transformed?.code) throw new Error('Babel returned no compatibility script.');
  const script = `${polyfills.trim()}\n${transformed.code.trim()}\n`;

  html = html
    .replace(
      /<script\s+type="module"\s+data-csp-hash>[\s\S]*?<\/script>/,
      `<script data-csp-hash>\n${script}    </script>`,
    )
    .replace('<title>影視 OKTV iPhone</title>', '<title>影視 OKTV 車機相容版</title>')
    .replace('<head>', '<head>\n    <!-- Bundled compatibility page; generated by android-car/tools/build-compat-page.mjs. -->');

  const style = exactlyOne(html, /<style\s+data-csp-hash>([\s\S]*?)<\/style>/g, 'style block');
  const classicScript = exactlyOne(html, /<script\s+data-csp-hash>([\s\S]*?)<\/script>/g, 'classic script');
  const policy = compatibilityPolicy(style, classicScript);
  html = html.replace(
    /<meta\s+http-equiv="Content-Security-Policy"\s+data-oktv-csp\s+content="[^"]*"\s*\/?>/,
    `<meta http-equiv="Content-Security-Policy" data-oktv-csp content="${policy}" />`,
  );

  await fs.mkdir(path.dirname(outputFile), { recursive: true });
  await fs.writeFile(outputFile, html, 'utf8');
  console.log(
    JSON.stringify(
      {
        inputFile,
        outputFile,
        target: 'Chrome 49 / Android 5+',
        bytes: Buffer.byteLength(html),
        scriptHash: sha256(classicScript),
        styleHash: sha256(style),
      },
      null,
      2,
    ),
  );
}

await main();
